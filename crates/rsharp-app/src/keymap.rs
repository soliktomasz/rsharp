//! The keys, as Rider's: its macOS keymap on macOS and its Visual Studio keymap elsewhere.

use crate::editor::*;
use crate::find_action::{Choose, Dismiss, SelectNext, SelectPrevious};
use crate::find_bar::{CloseFind, Find, FindNext, FindPrevious, Replace, ReplaceOne};
use crate::window::*;
use gpui::{App, KeyBinding};

gpui::actions!(app, [Quit, OpenSettings]);

pub fn bind(cx: &mut App) {
    let editor = Some("CodeEditor");
    let explorer = Some("Explorer");
    let mac = cfg!(target_os = "macos");
    cx.bind_keys([
        KeyBinding::new(if mac { "cmd-k" } else { "ctrl-k" }, ToggleCommit, None),
        KeyBinding::new(if mac { "cmd-9" } else { "alt-9" }, ToggleGit, None),
        KeyBinding::new(if mac { "cmd-shift-k" } else { "ctrl-shift-k" }, GitPush, None),
        KeyBinding::new(if mac { "cmd-t" } else { "ctrl-alt-y" }, GitUpdate, None),
        KeyBinding::new("ctrl-alt-down", NextChange, editor),
        KeyBinding::new("ctrl-alt-up", PreviousChange, editor),
        // Rider's own key for the Terminal tool window, the same on both platforms.
        KeyBinding::new("alt-f12", ToggleTerminal, None),
        KeyBinding::new("left", Left, editor),
        KeyBinding::new("right", Right, editor),
        KeyBinding::new("up", Up, editor),
        KeyBinding::new("down", Down, editor),
        KeyBinding::new("shift-left", SelectLeft, editor),
        KeyBinding::new("shift-right", SelectRight, editor),
        KeyBinding::new("shift-up", SelectUp, editor),
        KeyBinding::new("shift-down", SelectDown, editor),
        KeyBinding::new("home", LineStart, editor),
        KeyBinding::new("end", LineEnd, editor),
        KeyBinding::new("shift-home", SelectLineStart, editor),
        KeyBinding::new("shift-end", SelectLineEnd, editor),
        KeyBinding::new("pageup", PageUp, editor),
        KeyBinding::new("pagedown", PageDown, editor),
        KeyBinding::new("backspace", Backspace, editor),
        KeyBinding::new("delete", Delete, editor),
        KeyBinding::new("enter", Newline, editor),
        KeyBinding::new("tab", Tab, editor),
        KeyBinding::new("secondary-a", SelectAll, editor),
        KeyBinding::new("secondary-c", Copy, editor),
        KeyBinding::new("secondary-x", Cut, editor),
        KeyBinding::new("secondary-v", Paste, editor),
        KeyBinding::new("secondary-z", Undo, editor),
        KeyBinding::new("escape", Escape, editor),
        // Rider has no key for these on macOS (Option pressed twice, then held); Passenger's are taken on both.
        KeyBinding::new("alt-shift-up", CloneCaretAbove, editor),
        KeyBinding::new("alt-shift-down", CloneCaretBelow, editor),
        KeyBinding::new("alt-shift-g", CaretPerLine, editor),
        KeyBinding::new(if mac { "cmd-shift-8" } else { "alt-shift-insert" }, ToggleColumnMode, editor),
        KeyBinding::new("secondary-s", Save, None),
        KeyBinding::new("secondary-f", Find, None),
        KeyBinding::new(if mac { "cmd-r" } else { "ctrl-h" }, Replace, None),
        KeyBinding::new(if mac { "cmd-g" } else { "f3" }, FindNext, None),
        KeyBinding::new(if mac { "cmd-shift-g" } else { "shift-f3" }, FindPrevious, None),
        KeyBinding::new("enter", FindNext, Some("FindBar")),
        KeyBinding::new("shift-enter", FindPrevious, Some("FindBar")),
        KeyBinding::new("escape", CloseFind, Some("FindBar")),
        KeyBinding::new("enter", ReplaceOne, Some("ReplaceField")),
        KeyBinding::new("secondary-w", CloseTab, None),
        KeyBinding::new("shift-f4", OpenTabInNewWindow, None),
        KeyBinding::new(if mac { "cmd-1" } else { "alt-1" }, ToggleSolution, None),
        KeyBinding::new(if mac { "cmd-6" } else { "alt-6" }, ToggleProblems, None),
        KeyBinding::new(if mac { "cmd-7" } else { "alt-7" }, ToggleNuGet, None),
        KeyBinding::new(if mac { "cmd-shift-b" } else { "ctrl-shift-b" }, BuildSolution, None),
        KeyBinding::new(if mac { "cmd-0" } else { "alt-0" }, ToggleBuild, None),
        KeyBinding::new("shift-f5", Stop, None),
        KeyBinding::new("f5", DebugProgram, None),
        KeyBinding::new("f5", ResumeDebug, None),
        KeyBinding::new("f9", ToggleBreakpoint, editor),
        KeyBinding::new(if mac { "cmd-shift-f8" } else { "ctrl-shift-f8" }, ShowBreakpoints, None),
        KeyBinding::new("f10", StepOver, None),
        KeyBinding::new("f11", StepInto, None),
        KeyBinding::new("shift-f11", StepOut, None),
        // Rider's Visual Studio keymap breaks all programs with Ctrl+Alt+Break, which gpui has no key for.
        KeyBinding::new("ctrl-alt-p", PauseDebug, None),
        KeyBinding::new("alt-f8", EvaluateExpression, None),
        // Rider's Visual Studio keymap's; its macOS keymap leaves Set Next Statement to the menu.
        KeyBinding::new("ctrl-shift-f10", SetNextStatement, None),
        KeyBinding::new("enter", crate::debug_view::ApplySetValue, Some("DebugWindow")),
        KeyBinding::new("escape", Dismiss, Some("EvaluateDialog")),
        KeyBinding::new("enter", Choose, Some("EvaluateDialog")),
        KeyBinding::new("ctrl-f5", RunProgram, None),
        KeyBinding::new(if mac { "alt-shift-f5" } else { "ctrl-shift-f5" }, RerunProgram, None),
        KeyBinding::new(if mac { "cmd-4" } else { "alt-4" }, ToggleRun, None),
        KeyBinding::new(if mac { "cmd-8" } else { "alt-8" }, ToggleUnitTests, None),
        KeyBinding::new("ctrl-u r", RunTests, None),
        KeyBinding::new("ctrl-u ctrl-r", RunTests, None),
        KeyBinding::new("ctrl-u f", RerunFailedTests, None),
        KeyBinding::new("ctrl-u ctrl-f", RerunFailedTests, None),
        KeyBinding::new("alt-f10", ApplyHotReloadChanges, None),
        KeyBinding::new("up", SelectPrevious, Some("NuGet")),
        KeyBinding::new("down", SelectNext, Some("NuGet")),
        KeyBinding::new("up", SelectPrevious, Some("UnitTests")),
        KeyBinding::new("down", SelectNext, Some("UnitTests")),
        KeyBinding::new("shift-escape", HideToolWindow, None),
        KeyBinding::new("shift-f12", RestoreDefaultLayout, None),
        KeyBinding::new("up", ExplorerUp, explorer),
        KeyBinding::new("down", ExplorerDown, explorer),
        KeyBinding::new("right", ExplorerExpand, explorer),
        KeyBinding::new("left", ExplorerCollapse, explorer),
        KeyBinding::new("enter", ExplorerOpen, explorer),
        KeyBinding::new("up", SelectPrevious, Some("ReferenceDialog")),
        KeyBinding::new("down", SelectNext, Some("ReferenceDialog")),
        KeyBinding::new("space", crate::reference_dialog::ToggleChoice, Some("ReferenceDialog")),
        KeyBinding::new("enter", Choose, Some("ReferenceDialog")),
        KeyBinding::new("escape", Dismiss, Some("ReferenceDialog")),
        KeyBinding::new("up", SelectPrevious, Some("NamePopup")),
        KeyBinding::new("down", SelectNext, Some("NamePopup")),
        KeyBinding::new("enter", Choose, Some("NamePopup")),
        KeyBinding::new("escape", Dismiss, Some("NamePopup")),
        KeyBinding::new("secondary-shift-a", FindAction, None),
        KeyBinding::new("secondary-shift-n", NewProject, Some("MainWindow")),
        KeyBinding::new("up", SelectPrevious, Some("FindAction")),
        KeyBinding::new("down", SelectNext, Some("FindAction")),
        KeyBinding::new("enter", Choose, Some("FindAction")),
        KeyBinding::new("escape", Dismiss, Some("FindAction")),
        KeyBinding::new("escape", Dismiss, Some("AttachDialog")),
        KeyBinding::new("enter", Choose, Some("AttachDialog")),
        KeyBinding::new("up", SelectPrevious, Some("AttachDialog")),
        KeyBinding::new("down", SelectNext, Some("AttachDialog")),
        KeyBinding::new("escape", Dismiss, Some("BreakpointsDialog")),
        KeyBinding::new("enter", Choose, Some("BreakpointsDialog")),
        KeyBinding::new("escape", Dismiss, Some("SettingsDialog")),
        KeyBinding::new("enter", Choose, Some("SettingsDialog")),
        KeyBinding::new("escape", Dismiss, Some("NewProjectDialog")),
        KeyBinding::new("enter", Choose, Some("NewProjectDialog")),
        KeyBinding::new("up", SelectPrevious, Some("NewProjectDialog")),
        KeyBinding::new("down", SelectNext, Some("NewProjectDialog")),
        KeyBinding::new("tab", crate::new_project_dialog::NextField, Some("NewProjectDialog")),
        KeyBinding::new("shift-tab", crate::new_project_dialog::PreviousField, Some("NewProjectDialog")),
        KeyBinding::new("space", crate::new_project_dialog::ActivateControl, Some("ProjectControl")),
        // The field's editing keys are the editor's own.
        KeyBinding::new("left", Left, Some("TextField")),
        KeyBinding::new("right", Right, Some("TextField")),
        KeyBinding::new("shift-left", SelectLeft, Some("TextField")),
        KeyBinding::new("shift-right", SelectRight, Some("TextField")),
        KeyBinding::new("home", LineStart, Some("TextField")),
        KeyBinding::new("end", LineEnd, Some("TextField")),
        KeyBinding::new("backspace", Backspace, Some("TextField")),
        KeyBinding::new("delete", Delete, Some("TextField")),
        KeyBinding::new("secondary-a", SelectAll, Some("TextField")),
        KeyBinding::new("secondary-c", Copy, Some("TextField")),
        KeyBinding::new("secondary-x", Cut, Some("TextField")),
        KeyBinding::new("secondary-v", Paste, Some("TextField")),
        KeyBinding::new("ctrl-space", Complete, editor),
        KeyBinding::new("alt-enter", ShowContextActions, editor),
        KeyBinding::new("enter", Choose, Some("RenamePopup")),
        KeyBinding::new("escape", Dismiss, Some("RenamePopup")),
        KeyBinding::new("enter", Choose, Some("RefactorDialog")),
        KeyBinding::new("escape", Dismiss, Some("RefactorDialog")),
    ]);
    if mac {
        cx.bind_keys([
            KeyBinding::new("cmd-n", SolutionNew, explorer),
            KeyBinding::new("shift-f6", SolutionRename, explorer),
            KeyBinding::new("backspace", SolutionDelete, explorer),
            KeyBinding::new("cmd-backspace", SolutionDelete, explorer),
            KeyBinding::new("cmd-x", SolutionCut, explorer),
            KeyBinding::new("cmd-c", SolutionCopy, explorer),
            KeyBinding::new("cmd-v", SolutionPaste, explorer),
        ]);
        cx.bind_keys([
            KeyBinding::new("alt-left", WordLeft, editor),
            KeyBinding::new("alt-right", WordRight, editor),
            KeyBinding::new("alt-shift-left", SelectWordLeft, editor),
            KeyBinding::new("alt-shift-right", SelectWordRight, editor),
            KeyBinding::new("cmd-left", LineStart, editor),
            KeyBinding::new("cmd-right", LineEnd, editor),
            KeyBinding::new("cmd-shift-left", SelectLineStart, editor),
            KeyBinding::new("cmd-shift-right", SelectLineEnd, editor),
            KeyBinding::new("cmd-up", DocumentStart, editor),
            KeyBinding::new("cmd-down", DocumentEnd, editor),
            KeyBinding::new("cmd-shift-up", SelectDocumentStart, editor),
            KeyBinding::new("cmd-shift-down", SelectDocumentEnd, editor),
            KeyBinding::new("cmd-shift-z", Redo, editor),
            KeyBinding::new("ctrl-g", SelectNextOccurrence, editor),
            KeyBinding::new("ctrl-m", MatchBrace, editor),
            KeyBinding::new("cmd-=", ExpandRegion, editor),
            KeyBinding::new("cmd-+", ExpandRegion, editor),
            KeyBinding::new("cmd--", CollapseRegion, editor),
            KeyBinding::new("cmd-shift-=", ExpandAll, editor),
            KeyBinding::new("cmd-shift-+", ExpandAll, editor),
            KeyBinding::new("cmd-shift--", CollapseAll, editor),
            KeyBinding::new("cmd-shift-_", CollapseAll, editor),
            KeyBinding::new("ctrl-shift-.", IncreaseFontSize, editor),
            KeyBinding::new("ctrl-shift-,", DecreaseFontSize, editor),
            KeyBinding::new("ctrl-shift-g", UnselectOccurrence, editor),
            KeyBinding::new("ctrl-cmd-g", SelectAllOccurrences, editor),
            KeyBinding::new("cmd-p", ParameterInfo, editor),
            KeyBinding::new("f1", QuickDocumentation, editor),
            KeyBinding::new("shift-f6", Rename, editor),
            KeyBinding::new("cmd-alt-l", Reformat, editor),
            KeyBinding::new("cmd-b", GoToDeclaration, editor),
            KeyBinding::new("cmd-alt-b", GoToImplementation, editor),
            KeyBinding::new("cmd-shift-f11", GoToTypeDeclaration, editor),
            KeyBinding::new("alt-f7", FindUsages, editor),
            // Rider's macOS keymap: Super Method (Base Symbols) is Cmd+U; Derived Symbols has no key of its own there.
            KeyBinding::new("cmd-u", BaseSymbols, editor),
            KeyBinding::new("ctrl-alt-o", OptimizeUsings, editor),
            KeyBinding::new("cmd-alt-v", IntroduceVariable, editor),
            KeyBinding::new("cmd-alt-f", IntroduceField, editor),
            KeyBinding::new("cmd-alt-p", IntroduceParameter, editor),
            KeyBinding::new("cmd-alt-m", ExtractMethod, editor),
            KeyBinding::new("cmd-alt-n", Inline, editor),
            KeyBinding::new("cmd-delete", SafeDelete, editor),
            KeyBinding::new("cmd-alt-t", SurroundWith, editor),
            KeyBinding::new("cmd-shift-enter", CompleteStatement, editor),
            KeyBinding::new("cmd-f6", ChangeSignature, editor),
            KeyBinding::new("f6", MoveType, editor),
            // Rider's macOS keymap gives Open no key: Cmd+O is Go to Type.
            KeyBinding::new("cmd-[", Back, None),
            KeyBinding::new("cmd-]", Forward, None),
            KeyBinding::new("cmd-shift-backspace", LastEditLocation, None),
            KeyBinding::new("cmd-e", RecentFiles, None),
            KeyBinding::new("cmd-shift-o", GoToFile, None),
            KeyBinding::new("cmd-o", GoToType, None),
            KeyBinding::new("cmd-alt-o", GoToSymbol, None),
            KeyBinding::new("cmd-shift-f", FindInFiles, None),
            KeyBinding::new("cmd-shift-r", ReplaceInFiles, None),
            KeyBinding::new("cmd-shift-e", RecentLocations, None),
            KeyBinding::new("cmd-q", Quit, None),
            KeyBinding::new("cmd-,", OpenSettings, None),
            KeyBinding::new("alt-left", WordLeft, Some("TextField")),
            KeyBinding::new("alt-right", WordRight, Some("TextField")),
            KeyBinding::new("cmd-left", LineStart, Some("TextField")),
            KeyBinding::new("cmd-right", LineEnd, Some("TextField")),
        ]);
    } else {
        cx.bind_keys([
            KeyBinding::new("alt-insert", SolutionNew, explorer),
            KeyBinding::new("f2", SolutionRename, explorer),
            KeyBinding::new("delete", SolutionDelete, explorer),
            KeyBinding::new("ctrl-x", SolutionCut, explorer),
            KeyBinding::new("ctrl-c", SolutionCopy, explorer),
            KeyBinding::new("ctrl-v", SolutionPaste, explorer),
        ]);
        cx.bind_keys([
            KeyBinding::new("ctrl-left", WordLeft, editor),
            KeyBinding::new("ctrl-right", WordRight, editor),
            KeyBinding::new("ctrl-shift-left", SelectWordLeft, editor),
            KeyBinding::new("ctrl-shift-right", SelectWordRight, editor),
            KeyBinding::new("ctrl-home", DocumentStart, editor),
            KeyBinding::new("ctrl-end", DocumentEnd, editor),
            KeyBinding::new("ctrl-shift-home", SelectDocumentStart, editor),
            KeyBinding::new("ctrl-shift-end", SelectDocumentEnd, editor),
            KeyBinding::new("ctrl-y", Redo, editor),
            KeyBinding::new("ctrl-shift-z", Redo, editor),
            KeyBinding::new("alt-shift-.", SelectNextOccurrence, editor),
            KeyBinding::new("ctrl-]", MatchBrace, editor),
            KeyBinding::new("ctrl-m ctrl-m", ToggleFold, editor),
            KeyBinding::new("ctrl-m m", ToggleFold, editor),
            KeyBinding::new("ctrl-m ctrl-e", ExpandRegion, editor),
            KeyBinding::new("ctrl-m e", ExpandRegion, editor),
            KeyBinding::new("ctrl-m ctrl-s", CollapseRegion, editor),
            KeyBinding::new("ctrl-m s", CollapseRegion, editor),
            KeyBinding::new("ctrl-m ctrl-x", ExpandAll, editor),
            KeyBinding::new("ctrl-m x", ExpandAll, editor),
            KeyBinding::new("ctrl-m ctrl-a", CollapseAll, editor),
            KeyBinding::new("ctrl-m a", CollapseAll, editor),
            KeyBinding::new("ctrl-e ctrl-w", ToggleSoftWrap, editor),
            KeyBinding::new("ctrl-e w", ToggleSoftWrap, editor),
            KeyBinding::new("alt-shift-,", UnselectOccurrence, editor),
            KeyBinding::new("alt-shift-;", SelectAllOccurrences, editor),
            KeyBinding::new("ctrl-shift-space", ParameterInfo, editor),
            KeyBinding::new("ctrl-k ctrl-i", QuickDocumentation, editor),
            KeyBinding::new("ctrl-shift-f1", QuickDocumentation, editor),
            KeyBinding::new("ctrl-.", ShowContextActions, editor),
            KeyBinding::new("ctrl-r ctrl-r", Rename, editor),
            KeyBinding::new("ctrl-r r", Rename, editor),
            KeyBinding::new("ctrl-k ctrl-d", Reformat, editor),
            KeyBinding::new("ctrl-k d", Reformat, editor),
            KeyBinding::new("ctrl-alt-enter", Reformat, editor),
            KeyBinding::new("f12", GoToDeclaration, editor),
            KeyBinding::new("ctrl-f12", GoToImplementation, editor),
            KeyBinding::new("ctrl-shift-f11", GoToTypeDeclaration, editor),
            KeyBinding::new("shift-f12", FindUsages, editor),
            KeyBinding::new("alt-home", BaseSymbols, editor),
            KeyBinding::new("ctrl-r ctrl-g", OptimizeUsings, editor),
            KeyBinding::new("ctrl-alt-o", OptimizeUsings, editor),
            KeyBinding::new("ctrl-r ctrl-v", IntroduceVariable, editor),
            KeyBinding::new("ctrl-r ctrl-f", IntroduceField, editor),
            KeyBinding::new("ctrl-r ctrl-p", IntroduceParameter, editor),
            KeyBinding::new("ctrl-r ctrl-e", EncapsulateField, editor),
            KeyBinding::new("ctrl-r ctrl-m", ExtractMethod, editor),
            KeyBinding::new("ctrl-r ctrl-i", Inline, editor),
            KeyBinding::new("ctrl-r ctrl-d", SafeDelete, editor),
            KeyBinding::new("alt-delete", SafeDelete, editor),
            KeyBinding::new("ctrl-e ctrl-u", SurroundWith, editor),
            KeyBinding::new("ctrl-k ctrl-s", SurroundWith, editor),
            KeyBinding::new("ctrl-shift-enter", CompleteStatement, editor),
            KeyBinding::new("ctrl-r ctrl-s", ChangeSignature, editor),
            KeyBinding::new("ctrl-r ctrl-o", MoveType, editor),
            KeyBinding::new("alt-end", DerivedSymbols, editor),
            KeyBinding::new("ctrl-o", OpenFolder, None),
            KeyBinding::new("ctrl--", Back, None),
            KeyBinding::new("ctrl-shift--", Forward, None),
            KeyBinding::new("ctrl-shift-backspace", LastEditLocation, None),
            KeyBinding::new("ctrl-,", RecentFiles, None),
            KeyBinding::new("ctrl-shift-t", GoToFile, None),
            // Rider's Visual Studio keymap: Ctrl+T is Go to Everything; Go to Type has no key of its own there.
            KeyBinding::new("ctrl-t", SearchEverywhere, None),
            KeyBinding::new("ctrl-shift-h", ReplaceInFiles, None),
            KeyBinding::new("ctrl-shift-e", RecentLocations, None),
            KeyBinding::new("ctrl-shift-alt-t", GoToSymbol, None),
            KeyBinding::new("ctrl-shift-f", FindInFiles, None),
            KeyBinding::new("alt-f4", Quit, None),
            KeyBinding::new("ctrl-alt-s", OpenSettings, None),
            KeyBinding::new("ctrl-left", WordLeft, Some("TextField")),
            KeyBinding::new("ctrl-right", WordRight, Some("TextField")),
        ]);
    }
}
